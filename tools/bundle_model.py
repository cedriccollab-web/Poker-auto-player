"""
Build model.py, the submitted bot, as one self-contained file.

The organisers' form asks for the .pkl and model.py, so model.py must not
need any other team file. The sources stay split for development:

    preflop_table.py  equity.py  opponent.py  strategy.py  ->  model.py

Run from the repo root after editing any of them:

    python tools/bundle_model.py

tests/test_bundle.py fails when model.py is out of date with its sources.
"""

import ast
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCES = ["preflop_table.py", "equity.py", "opponent.py", "strategy.py"]
BUNDLED = {name[:-3] for name in SOURCES}

HEADER = '''"""
Team Prefer not to say: the whole bot in one file.

GENERATED by tools/bundle_model.py from {sources}.
Do not edit this file: edit those sources and run
`python tools/bundle_model.py`. tests/test_bundle.py checks it is current.

{strategy_doc}
"""
'''


def _split(path):
    """(docstring, import lines not of bundled modules, body without its
    docstring and imports) of one source file."""
    text = open(path, encoding="utf-8").read()
    tree = ast.parse(text)
    lines = text.splitlines()
    drop = set()
    doc = ""
    imports = []
    body = tree.body
    if body and isinstance(body[0], ast.Expr) and isinstance(
            getattr(body[0], "value", None), ast.Constant) and isinstance(
            body[0].value.value, str):
        doc = body[0].value.value.strip()
        drop.update(range(body[0].lineno - 1, body[0].end_lineno))
    for node in body:
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            drop.update(range(node.lineno - 1, node.end_lineno))
            module = node.module if isinstance(node, ast.ImportFrom) else None
            names = [a.name for a in node.names]
            if module in BUNDLED or any(n in BUNDLED for n in names):
                continue
            imports.append("\n".join(lines[node.lineno - 1:node.end_lineno]))
    kept = [line for i, line in enumerate(lines) if i not in drop]
    return doc, imports, "\n".join(kept).strip("\n")


def build():
    parts, imports, strategy_doc = [], [], ""
    for name in SOURCES:
        doc, imps, body = _split(os.path.join(ROOT, name))
        if name == "strategy.py":
            strategy_doc = doc
        for imp in imps:
            if imp not in imports:
                imports.append(imp)
        parts.append(f"# {'-' * 20} from {name} {'-' * 20}\n\n{body}\n")
    header = HEADER.format(sources=", ".join(SOURCES), strategy_doc=strategy_doc)
    stdlib = sorted(i for i in imports if i.split()[1].split(".")[0] in sys.stdlib_module_names)
    local = sorted(i for i in imports if i not in stdlib)
    return (header + "\n" + "\n".join(stdlib) + "\n\n" + "\n".join(local)
            + "\n\n\n" + "\n\n".join(parts))


if __name__ == "__main__":
    out = os.path.join(ROOT, "model.py")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(build())
    print("wrote", out)
